assert.equal(/^hmac-sha256:v[1-9][0-9]{0,4}:[a-z0-9][a-z0-9._:-]{0,127}:[0-9a-f]{64}$/.test(representative.mutations[0].value), false);
const badDetector = structuredClone(detector); badDetector.classes[0].defaultAction = 'DENY'; assert.equal(new Ajv().compile(detectorSchema)(badDetector), false);
const badCase = structuredClone(neutral.case); badCase.provenance.license = ''; assert.equal(new Ajv().compile(neutralSchema)(badCase), false);
process.stdout.write('M4.7 contract-spine schemas/fixtures: PASS\n');
