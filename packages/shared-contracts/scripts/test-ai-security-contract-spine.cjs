'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Ajv = require('ajv');
const root = path.resolve(__dirname, '..');
const read = (file) => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
const validate = (schema, value) => { const fn = new Ajv({ allErrors: true, strict: true }).compile(schema); assert.equal(fn(value), true, JSON.stringify(fn.errors)); };
const detectorSchema = read('schemas/ai-security-detector-catalog-v1.schema.json');
const detector = read('fixtures/ai-security-detector-catalog.v1.json');
validate(detectorSchema, detector);
const neutralSchema = read('schemas/ai-security-neutral-evaluation-v1.schema.json');
const neutral = read('fixtures/ai-security-neutral-evaluation.v1.json');
validate(neutralSchema, neutral.case); validate(neutralSchema, neutral.result);
const hmac = read('fixtures/ai-security-hmac-domain-catalog.v1.json');
assert.equal(hmac.productionWriterEnabled, false); assert.equal(hmac.domains.every((row) => row.writerEnabled === false), true); assert.equal(new Set(hmac.domains.map((row) => row.domain)).size, 12);
const wireSchema = read('schemas/ai-security-v2-wire-v1.schema.json');
const representative = read('fixtures/ai-security-v2-wire-representative.v1.json');
const validateWire = new Ajv({ allErrors: true, strict: true }).compile(wireSchema);
for (const record of representative.records) assert.equal(validateWire(record), true, JSON.stringify(validateWire.errors));
const unknownRecordProperty = structuredClone(representative.records[1]); unknownRecordProperty.unknown = true; assert.equal(validateWire(unknownRecordProperty), false);
